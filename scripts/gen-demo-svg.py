"""Generates docs/assets/demo.svg, the animated side-by-side terminal in the README.

Why a generated SVG and not a GIF: GitHub renders an SVG <img> crisply at any zoom, in
light AND dark mode, at a few KB, and its text stays real text. Every line needs its own
keyframe timing, which is tedious and error-prone by hand, hence this script.
Run:  python scripts/gen-demo-svg.py
"""
from html import escape

W, H = 900, 372
CYCLE = 18.0  # seconds for one full play
PAD, GAP = 20, 20
PW = (W - 2 * PAD - GAP) / 2
TOP = 78
LH = 22

left = [
    ("cmd", '$ claude "add a retry to the uploads"'),
    ("out", "› Let me explore the repo first…"),
    ("out", "› reading 41 files…"),
    ("out", "› Added a retry loop to upload.ts ✓"),
    ("you", "you: we tried that in March."),
    ("you", "     It broke the job queue."),
    ("out", "› Sorry, I didn't know that."),
]
right = [
    ("cmd", '$ claude "add a retry to the uploads"'),
    ("out", "› reading BRAIN.md…"),
    ("hot", "› §5 GOTCHA: retries on upload break"),
    ("hot", "  the job queue (tried in March)"),
    ("out", "› plan: client-side backoff instead"),
    ("out", "› builder ✓   test-writer ✓"),
    ("bad", "› qa: FAILED · backoff test never ran"),
    ("bad", "  → back to the builder"),
    ("ok",  "› qa: VALIDATED · reviewer: PASS"),
    ("hot", "› BRAIN.md written · left off: …"),
]
foot_l = ("bad", "✖ re-learned the hard way. Again.")
foot_r = ("ok", "✔ answered from the brain, gated by the crew")

STEP = 1.25  # seconds between lines
START = 0.6

css_lines, body = [], []
n = 0

def line(x, y, kind, text, t):
    global n
    n += 1
    p = t / CYCLE * 100
    name = f"l{n}"
    css_lines.append(
        f"@keyframes {name}{{0%,{max(p-0.01,0):.2f}%{{opacity:0}}{p:.2f}%,93%{{opacity:1}}97%,100%{{opacity:0}}}}"
        f".{name}{{animation:{name} {CYCLE}s linear infinite}}"
    )
    body.append(f'<text x="{x:.0f}" y="{y:.0f}" class="{kind} {name}">{escape(text)}</text>')

def pane(x0, title, lines, foot, accent):
    body.append(f'<rect class="pane" x="{x0:.0f}" y="20" width="{PW:.0f}" height="{H-40}" rx="12"/>')
    body.append(f'<rect class="bar" x="{x0:.0f}" y="20" width="{PW:.0f}" height="34" rx="12"/>')
    body.append(f'<rect class="bar" x="{x0:.0f}" y="40" width="{PW:.0f}" height="14"/>')
    for i, c in enumerate(("#ff5f57", "#febc2e", "#28c840")):
        body.append(f'<circle cx="{x0+20+i*18:.0f}" cy="37" r="5.5" fill="{c}"/>')
    body.append(f'<text x="{x0+PW/2:.0f}" y="42" text-anchor="middle" class="title {accent}">{escape(title)}</text>')
    for i, (k, t) in enumerate(lines):
        line(x0 + 18, TOP + 10 + i * LH, k, t, START + i * STEP)
    last = START + len(right) * STEP  # both footers land together, after the longer pane
    line(x0 + 18, H - 40, foot[0] + " foot", foot[1], last)

pane(PAD, "without a brain", left, foot_l, "t-bad")
pane(PAD + PW + GAP, "with brain-kit", right, foot_r, "t-ok")

svg = f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" width="{W}" height="{H}" role="img" aria-labelledby="t d">
<title id="t">The same request, without and with a brain</title>
<desc id="d">Left: the agent explores 41 files and repeats a mistake the team already made in March. Right: the agent reads BRAIN.md, finds the gotcha about retries breaking the job queue, plans a client-side backoff instead, qa sends the work back once because a test never ran, then qa validates, the reviewer passes it, and the brain is written for the next session.</desc>
<!-- GENERATED by scripts/gen-demo-svg.py — edit the script, not this file. -->
<style>
:root{{--bg:#ffffff;--pane:#0d1117;--bar:#161b22;--ink:#e6edf3;--mute:#8b949e;--cmd:#79c0ff;--you:#f0b72f;--hot:#c4b5fd;--bad:#ff7b72;--ok:#3fb950}}
@media (prefers-color-scheme:dark){{:root{{--bg:#0d1117;--pane:#010409;--bar:#161b22}}}}
text{{white-space:pre;font-family:ui-monospace,SFMono-Regular,Menlo,Consolas,"Liberation Mono",monospace;font-size:13.5px;fill:var(--ink)}}
.bgr{{fill:var(--bg)}} .pane{{fill:var(--pane);stroke:#30363d}} .bar{{fill:var(--bar)}}
.title{{font-family:ui-sans-serif,system-ui,-apple-system,"Segoe UI",sans-serif;font-size:13px;font-weight:700;letter-spacing:.04em}}
.t-bad{{fill:var(--bad)}} .t-ok{{fill:var(--ok)}}
.cmd{{fill:var(--cmd)}} .out{{fill:var(--ink)}} .you{{fill:var(--you)}} .hot{{fill:var(--hot)}} .bad{{fill:var(--bad)}} .ok{{fill:var(--ok)}}
.foot{{font-weight:700;font-size:14px}}
{"".join(css_lines)}
@media (prefers-reduced-motion:reduce){{text{{animation:none!important;opacity:1!important}}}}
</style>
<rect class="bgr" width="{W}" height="{H}" rx="14"/>
{chr(10).join(body)}
</svg>
'''
open("docs/assets/demo.svg", "w", encoding="utf8").write(svg)
print("wrote docs/assets/demo.svg", len(svg), "bytes")
